"""Generate a small website evidence snapshot/assets from verified provenance.

Offline; no raw library, canonical artifact cache, network or inference needed.
"""

from __future__ import annotations
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated_files(root=ROOT):
    root = Path(root)
    publication = root / "provenance/publication-figures/2026-10-14"
    manifest = json.loads((publication / "figure_manifest.json").read_text())
    validation = json.loads((publication / "numerical_validation.json").read_text())
    sensor = root / "provenance/sensor-pft-transfer/2026-10-14"
    owned = json.loads((sensor / "statistics_manifest.json").read_text())[
        "evidence_outputs"
    ]

    def verified_csv(name):
        raw = (sensor / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != owned[name]:
            raise ValueError("Changed canonical sensor evidence: " + name)
        return list(csv.DictReader(io.StringIO(raw.decode())))

    retention = {r["scheme"]: r for r in verified_csv("retention_summary.csv")}
    effects = verified_csv("effect_retention.csv")
    c = validation["counts"]
    if manifest["panels"][1]["N"] != c or validation["status"] != "passed":
        raise ValueError("Publication count/validation mismatch")
    pft = retention["inferred_pft"]
    researcher = retention["researcher_category"]
    result = {
        "date": "2026-10-14",
        "source_sha256": validation["original_source_sha256"],
        "counts": c,
        "inferred_pft_retention": {
            k: pft[k] for k in ["eligible", "NEON_supported", "retained"]
        },
        "researcher_retention": {
            k: researcher[k] for k in ["eligible", "NEON_supported", "retained"]
        },
        "limitations": [
            "Stored library scale unresolved",
            "Synthetic OLI is not independent Landsat",
            "One next-day real-Landsat pilot",
            "MESMA operational readiness not established",
        ],
    }
    inferred = [r for r in effects if r["scheme"] == "inferred_pft"]
    if len(inferred) != int(pft["eligible"]):
        raise ValueError("Eligible comparison count mismatch")
    text = f"""<!-- Generated by scripts/generate_scientific_docs.py; source-specific, not package constants. -->

| Quantity | Verified snapshot (14 October 2026) |
|---|---:|
| Polygon / plant identities | {c["identities"]:,} |
| Polygon/year spectra | {c["polygon_years"]:,} |
| Extracted pixel records | {c["pixel_rows"]:,} |
| Identities with / without species recorded | {c["species_identified"]:,} / {c["species_missing"]:,} |
| Sites / acquisition years | {c["sites"]} / {c["years"]} |
| Researcher cover categories | {c["cover_categories"]} |

These are counts for the supplied polygon library, **not package limits**.
Repeated years are not additional independent plants. Species recorded means a
populated source field, not independently verified taxonomic resolution.
"""
    transfer = f"""<!-- Generated from verified canonical sensor-transfer tables. -->

| Label system | Eligible matched comparisons | NEON supported | Retained in synthetic OLI |
|---|---:|---:|---:|
| Inferred PFT | {pft["eligible"]} | {pft["NEON_supported"]} | {pft["retained"]} |
| Researcher cover category | {researcher["eligible"]} | {researcher["NEON_supported"]} | {researcher["retained"]} |

These are dependent contrast/cohort summaries, not independent trials or classification accuracies.
"""
    outputs = {
        root / "docs/spectral-library/_snapshot.md": text.encode(),
        root / "docs/spectral-library/_transfer.md": transfer.encode(),
        root / "docs/spectral-library/evidence-snapshot.json": (
            json.dumps(result, indent=2) + "\n"
        ).encode(),
    }
    for number, name in [
        (1, "Figure_1_spectral_library"),
        (2, "Figure_2_ecological_information"),
    ]:
        relative = f"output/pdf/publication_figures/{name}.png"
        raw = (root / relative).read_bytes()
        if hashlib.sha256(raw).hexdigest() != manifest["output_hashes"][relative]:
            raise ValueError("Changed publication image: " + name)
        outputs[root / f"docs/images/spectral-library/figure-{number}.png"] = raw
    pilot = root / "provenance/real-landsat-validation/2026-10-14"
    real_manifest = json.loads((pilot / "evidence_manifest.json").read_text())[
        "copied_files"
    ]
    name = "figures/A_side_by_side.png"
    raw = (pilot / name).read_bytes()
    if hashlib.sha256(raw).hexdigest() != real_manifest[name]:
        raise ValueError("Changed pilot comparison image")
    outputs[root / "docs/images/spectral-library/real-landsat-pilot.png"] = raw
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in generated_files().items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        raise SystemExit("Stale scientific docs: " + ", ".join(stale))
    print(
        "Scientific documentation snapshot/assets are current."
        if args.check
        else "Generated scientific documentation snapshot/assets."
    )


if __name__ == "__main__":
    main()
